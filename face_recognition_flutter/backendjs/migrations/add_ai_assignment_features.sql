DELIMITER //

-- Update daily AI statistics
CREATE PROCEDURE IF NOT EXISTS UpdateAIStats(IN target_date DATE)
BEGIN
    INSERT INTO ai_system_stats (
        date_recorded,
        total_generations,
        successful_generations,
        failed_generations,
        total_questions_generated,
        avg_generation_time_ms,
        avg_questions_per_generation,
        documents_processed,
        total_documents_size_mb,
        multiple_choice_count,
        short_answer_count,
        true_false_count,
        essay_count,
        easy_questions,
        medium_questions,
        hard_questions
    )
    SELECT 
        target_date,
        COUNT(*) as total_generations,
        SUM(CASE WHEN status = 'completed' THEN 1 ELSE 0 END) as successful_generations,
        SUM(CASE WHEN status = 'failed' THEN 1 ELSE 0 END) as failed_generations,
        SUM(questions_generated) as total_questions_generated,
        AVG(generation_time_ms) as avg_generation_time_ms,
        AVG(questions_generated) as avg_questions_per_generation,
        COUNT(*) as documents_processed,
        SUM(document_size_mb) as total_documents_size_mb,
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND question_type = 'multiple_choice'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND question_type = 'short_answer'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND question_type = 'true_false'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND question_type = 'essay'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND difficulty = 'easy'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND difficulty = 'medium'),
        (SELECT COUNT(*) FROM ai_template_questions WHERE DATE(created_at) = target_date AND difficulty = 'hard')
    FROM ai_generation_logs 
    WHERE DATE(created_at) = target_date
    ON DUPLICATE KEY UPDATE
        total_generations = VALUES(total_generations),
        successful_generations = VALUES(successful_generations),
        failed_generations = VALUES(failed_generations),
        total_questions_generated = VALUES(total_questions_generated),
        avg_generation_time_ms = VALUES(avg_generation_time_ms),
        avg_questions_per_generation = VALUES(avg_questions_per_generation),
        documents_processed = VALUES(documents_processed),
        total_documents_size_mb = VALUES(total_documents_size_mb),
        multiple_choice_count = VALUES(multiple_choice_count),
        short_answer_count = VALUES(short_answer_count),
        true_false_count = VALUES(true_false_count),
        essay_count = VALUES(essay_count),
        easy_questions = VALUES(easy_questions),
        medium_questions = VALUES(medium_questions),
        hard_questions = VALUES(hard_questions);
END //

DELIMITER ;

