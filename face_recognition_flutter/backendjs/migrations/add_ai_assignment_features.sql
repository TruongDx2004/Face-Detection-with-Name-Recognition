-- =====================================================
-- AI Template Questions Table
-- Stores individual questions generated by AI
-- =====================================================
CREATE TABLE IF NOT EXISTS ai_template_questions (
    id INT AUTO_INCREMENT PRIMARY KEY,
    template_id INT NOT NULL,
    generation_id VARCHAR(255) NOT NULL,
    
    -- Question details
    question_order INT NOT NULL DEFAULT 0,
    question_type ENUM('multiple_choice', 'short_answer', 'true_false', 'essay') NOT NULL,
    question_text TEXT NOT NULL,
    
    -- Type-specific content (stored as JSON for flexibility)
    options JSON NULL, -- For multiple choice: ["option1", "option2", "option3", "option4"]
    correct_answer TEXT NULL, -- Correct answer text
    sample_answer TEXT NULL, -- Sample answer for short answer/essay
    explanation TEXT NULL, -- Explanation of the answer
    rubric JSON NULL, -- For essay questions: ["criteria1", "criteria2", ...]
    
    -- Question metadata
    keywords JSON NULL, -- Keywords extracted from source text
    difficulty ENUM('easy', 'medium', 'hard') NOT NULL DEFAULT 'medium',
    estimated_time_minutes INT NOT NULL DEFAULT 2,
    complexity_score INT NOT NULL DEFAULT 1,
    max_score DECIMAL(5,2) NOT NULL DEFAULT 1.00,
    
    -- AI generation metadata
    source_chunk TEXT NULL, -- Original text chunk used to generate question
    ai_confidence DECIMAL(3,2) DEFAULT 0.80, -- AI confidence in question quality (0.0-1.0)
    processing_notes TEXT NULL, -- Any processing notes or warnings
    
    -- Quality metrics
    validation_passed BOOLEAN DEFAULT TRUE,
    quality_score DECIMAL(3,2) DEFAULT 0.75,
    
    -- Timestamps
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    -- Foreign keys
    FOREIGN KEY (template_id) REFERENCES assignment_templates(id) ON DELETE CASCADE,
    FOREIGN KEY (generation_id) REFERENCES ai_generation_logs(generation_id) ON DELETE CASCADE,
    
    -- Indexes
    INDEX idx_template_id (template_id),
    INDEX idx_generation_id (generation_id),
    INDEX idx_question_order (question_order),
    INDEX idx_question_type (question_type),
    INDEX idx_difficulty (difficulty)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================
-- AI System Statistics Table
-- Tracks overall system performance and usage
-- =====================================================
CREATE TABLE IF NOT EXISTS ai_system_stats (
    id INT AUTO_INCREMENT PRIMARY KEY,
    date_recorded DATE NOT NULL,
    
    -- Generation statistics
    total_generations INT DEFAULT 0,
    successful_generations INT DEFAULT 0,
    failed_generations INT DEFAULT 0,
    total_questions_generated INT DEFAULT 0,
    
    -- Performance metrics
    avg_generation_time_ms INT DEFAULT 0,
    avg_questions_per_generation DECIMAL(5,2) DEFAULT 0,
    avg_success_rate DECIMAL(5,2) DEFAULT 0,
    
    -- Document processing stats
    documents_processed INT DEFAULT 0,
    total_documents_size_mb DECIMAL(10,2) DEFAULT 0,
    most_common_format VARCHAR(20),
    
    -- Question type distribution
    multiple_choice_count INT DEFAULT 0,
    short_answer_count INT DEFAULT 0,
    true_false_count INT DEFAULT 0,
    essay_count INT DEFAULT 0,
    
    -- Difficulty distribution
    easy_questions INT DEFAULT 0,
    medium_questions INT DEFAULT 0,
    hard_questions INT DEFAULT 0,
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    UNIQUE KEY unique_date (date_recorded),
    INDEX idx_date_recorded (date_recorded)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

