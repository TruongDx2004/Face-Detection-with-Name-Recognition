-- =====================================================
-- AI Generation Logs Table
-- Tracks all AI assignment generation attempts
-- =====================================================
CREATE TABLE IF NOT EXISTS ai_generation_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    teacher_id INT NOT NULL,
    template_id INT NULL,
    generation_id VARCHAR(255) UNIQUE NOT NULL,
    document_name VARCHAR(255) NOT NULL,
    document_format VARCHAR(20) NOT NULL,
    document_size_mb DECIMAL(10,2) NOT NULL,
    questions_requested INT NOT NULL DEFAULT 10,
    questions_generated INT NOT NULL DEFAULT 0,
    generation_time_ms INT NOT NULL DEFAULT 0,
    success_rate DECIMAL(5,2) DEFAULT 0.00,
    
    -- Generation settings as JSON
    generation_settings JSON NOT NULL,
    
    -- Processing stages timing
    parsing_time_ms INT DEFAULT 0,
    preprocessing_time_ms INT DEFAULT 0,
    ai_generation_time_ms INT DEFAULT 0,
    postprocessing_time_ms INT DEFAULT 0,
    
    -- Status tracking
    status ENUM('pending', 'parsing', 'preprocessing', 'generating', 'postprocessing', 'saving', 'completed', 'failed') DEFAULT 'pending',
    error_message TEXT NULL,
    
    -- Timestamps
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    
    -- Foreign keys
    FOREIGN KEY (teacher_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (template_id) REFERENCES assignment_templates(id) ON DELETE SET NULL,
    
    -- Indexes for performance
    INDEX idx_teacher_id (teacher_id),
    INDEX idx_status (status),
    INDEX idx_created_at (created_at),
    INDEX idx_generation_id (generation_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

