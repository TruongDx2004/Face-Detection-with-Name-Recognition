-- AI Generation Summary View
CREATE OR REPLACE VIEW ai_generation_summary AS
SELECT 
    l.id,
    l.generation_id,
    l.teacher_id,
    u.full_name as teacher_name,
    l.document_name,
    l.document_format,
    l.questions_requested,
    l.questions_generated,
    l.generation_time_ms,
    l.success_rate,
    l.status,
    l.created_at,
    t.title as template_title,
    t.id as template_id
FROM ai_generation_logs l
LEFT JOIN users u ON l.teacher_id = u.id
LEFT JOIN assignment_templates t ON l.template_id = t.id
ORDER BY l.created_at DESC;

-- AI Questions Summary View  
CREATE OR REPLACE VIEW ai_questions_summary AS
SELECT 
    q.id,
    q.template_id,
    q.generation_id,
    q.question_type,
    q.difficulty,
    q.estimated_time_minutes,
    q.complexity_score,
    q.ai_confidence,
    q.quality_score,
    q.validation_passed,
    t.title as template_title,
    l.teacher_id,
    u.full_name as teacher_name
FROM ai_template_questions q
LEFT JOIN assignment_templates t ON q.template_id = t.id
LEFT JOIN ai_generation_logs l ON q.generation_id = l.generation_id
LEFT JOIN users u ON l.teacher_id = u.id
ORDER BY q.created_at DESC;

